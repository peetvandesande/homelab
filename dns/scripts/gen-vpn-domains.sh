#!/usr/bin/env bash
# Regenerate themis/etc/dnsdist/vpn-domains.conf from the router's VPN policy.
#
# The router is the source of truth. Its web UI writes
# /etc/domain_mac_list/<set>, so this repo must never claim ownership of that
# list - it derives from it and commits the result, which is what makes the
# drift check in verify.sh meaningful.
#
# Run this after changing a domain policy on the router, then commit the diff
# and ./scripts/deploy.sh.
set -euo pipefail

cd "$(dirname "$0")/.."
ROUTER=${ROUTER:-192.168.8.1}
SSH="ssh -o BatchMode=yes -o ConnectTimeout=5 -o StrictHostKeyChecking=accept-new root@$ROUTER"
OUT=${OUT:-themis/etc/dnsdist/vpn-domains.conf}

# Slugify a policy name into a dnsdist pool name: "UK" -> vpn-uk,
# "Main VPN" -> vpn-main-vpn. Pool names are referenced nowhere else, so the
# only requirement is that they are stable for a given policy name.
slug() { printf 'vpn-%s' "$(echo "$1" | tr '[:upper:]' '[:lower:]' | sed -e 's/[^a-z0-9]\+/-/g' -e 's/^-//' -e 's/-$//')"; }

policy_uci=$($SSH 'uci show route_policy') || { echo "cannot reach router at $ROUTER" >&2; exit 1; }

# Pull the ipset-based rules out of uci: index -> name/to/via.
# shellcheck disable=SC2016
mapfile -t rules < <(printf '%s\n' "$policy_uci" | awk -F'[][]|\\.|=' '
  /^route_policy\.@rule\[[0-9]+\]\.[a-z_]+=/ {
    idx=$3; key=$5; val=$0; sub(/^[^=]*=/, "", val); gsub(/^.|.$/, "", val); v[idx":"key]=val; seen[idx]=1
  }
  END { for (i in seen) if (v[i":to_type"]=="ipset" && v[i":enabled"]=="1")
          print v[i":name"] "\t" v[i":to"] "\t" v[i":via"] }' | sort)

tmp=$(mktemp); trap 'rm -f "$tmp"' EXIT
{
  echo "-- GENERATED by scripts/gen-vpn-domains.sh -- do not edit by hand."
  echo "--"
  echo "-- Mirrors the router's domain-based VPN policy. The router fills the"
  echo "-- destination ipset from the answers its own dnsmasq returns, so these"
  echo "-- names have to be resolved by the tunnel's dnsmasq instance rather than"
  echo "-- by Delphi - see dns/CLAUDE.md invariant 11."
  echo "--"
  echo "-- Source of truth: /etc/domain_mac_list/<set> on $ROUTER."
  echo "-- Regenerate with scripts/gen-vpn-domains.sh and commit the diff."
  echo
  echo "vpnPolicies = {"
} > "$tmp"

for rule in "${rules[@]}"; do
  IFS=$'\t' read -r name set via <<<"$rule"
  [[ -n "$set" && -n "$via" ]] || continue
  port=$($SSH "uci -q get dhcp.$via.port" || true)
  # A tunnel with no dnsmasq instance of its own cannot resolve through the
  # tunnel, and queries for its domains must not be shunted anywhere.
  [[ -n "$port" ]] || { echo "warn: $via has no dnsmasq instance; skipping '$name'" >&2; continue; }

  # Keep only the DNS entries. The same list also carries bare destination
  # IPs and prefixes, which the router adds to the set directly and which have
  # no DNS dimension at all. A domain never contains ':' or '/', and no TLD is
  # all digits, so this cannot mistake one for the other.
  mapfile -t domains < <($SSH "cat /etc/domain_mac_list/$set" \
    | awk '!/[:\/]/ && !/^([0-9]{1,3}\.){3}[0-9]{1,3}$/ && NF { print tolower($1) }' | sort -u)

  (( ${#domains[@]} )) || continue
  {
    printf '  {\n'
    printf '    pool     = "%s",\n' "$(slug "$name")"
    printf '    policy   = "%s",\n' "$name"
    printf '    tunnel   = "%s",\n' "$via"
    printf '    set      = "%s",\n' "$set"
    printf '    resolver = "%s:%s",\n' "$ROUTER" "$port"
    printf '    domains  = {\n'
    printf '      "%s",\n' "${domains[@]}"
    printf '    },\n  },\n'
  } >> "$tmp"
done

echo "}" >> "$tmp"
mv -f "$tmp" "$OUT"; trap - EXIT
echo "wrote $OUT"
grep -c '^      "' "$OUT" | xargs printf '  %s domain(s)\n'
